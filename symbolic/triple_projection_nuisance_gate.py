def calibrated_deprojection_residual() -> sp.Expr:
    sym = symbols()
    observed = sym["Gamma"] * relaxation_transfer() * sym["F_hat"]
    deprojected = sp.simplify(observed / (sym["Gamma"] * sym["F_hat"]))
    return sp.factor(sp.simplify(deprojected - relaxation_transfer()))


def range_deprojection_residual() -> sp.Expr:
    sym = symbols()
    projection = sym["Gamma"] / (sym["kappa"] ** 2 + sym["z"] ** 2)
    observed = projection * relaxation_transfer() * sym["F_hat"]
    deprojected = sp.simplify(
        observed * (sym["kappa"] ** 2 + sym["z"] ** 2)
        / (sym["Gamma"] * sym["F_hat"])
    )
    return sp.factor(sp.simplify(deprojected - relaxation_transfer()))


def arbitrary_projection_solution() -> sp.Expr:
    sym = symbols()
    return sp.simplify(sym["O_hat"] / (relaxation_transfer() * sym["F_hat"]))


def arbitrary_projection_reconstruction_residual() -> sp.Expr:
    sym = symbols()
    lambda_solution = arbitrary_projection_solution()
    reconstructed = sp.simplify(
        lambda_solution * relaxation_transfer() * sym["F_hat"]
    )
    return sp.factor(sp.simplify(reconstructed - sym["O_hat"]))


