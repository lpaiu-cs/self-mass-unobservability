@dataclass(frozen=True)
class ProjectionGateRow:
    term: str
    claim_status: str
    carrier_set: str
    projection_nuisance_class: str
    nuisance_parameterization: str
    nuisance_dimension: str
    comparator_pressure: str
    bridge_verdict: str
    runtime_relevance: str
    notes: str

    def __post_init__(self) -> None:
        if self.claim_status not in ALLOWED_CLAIM_STATUSES:
            allowed = ", ".join(sorted(ALLOWED_CLAIM_STATUSES))
            raise ValueError(
                f"claim_status must be one of {allowed}; got {self.claim_status!r}"
            )
        if self.bridge_verdict not in ALLOWED_BRIDGE_VERDICTS:
            allowed = ", ".join(sorted(ALLOWED_BRIDGE_VERDICTS))
            raise ValueError(
                f"bridge_verdict must be one of {allowed}; "
                f"got {self.bridge_verdict!r}"
            )
        if self.runtime_relevance not in ALLOWED_RUNTIME_RELEVANCE:
            allowed = ", ".join(sorted(ALLOWED_RUNTIME_RELEVANCE))
            raise ValueError(
                f"runtime_relevance must be one of {allowed}; "
                f"got {self.runtime_relevance!r}"
            )

    def to_row(self) -> dict[str, str]:
        return asdict(self)


def symbols() -> dict[str, sp.Symbol]:
    names = (
        "z tau_chi beta c_Y F_hat O_hat Gamma kappa "
        "q_k g0 g1 ell0 ell1"
    )
    return {name: sp.Symbol(name, nonzero=True) for name in names.split()}


def relaxation_transfer() -> sp.Expr:
    sym = symbols()
    return sym["c_Y"] + sym["beta"] / (1 + sym["tau_chi"] * sym["z"])


