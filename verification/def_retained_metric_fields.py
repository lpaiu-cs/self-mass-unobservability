def blend(v,t,old_t):
    j=np.clip(np.searchsorted(old_t,t,side='right')-1,0,len(old_t)-2)
    f=(t-old_t[j])/(old_t[j+1]-old_t[j]);f=f.reshape((-1,)+(1,)*(v.ndim-1))
    return (1-f)*v[j]+f*v[j+1]


