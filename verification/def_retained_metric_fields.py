class Lapse(metric.Lapse):
    run=FunctionType(metric.Lapse.run.__code__,dict(metric.Lapse.run.__globals__,OUT=METRIC))
    def boundary(self,d,steps,order):
        t=d['t'];end=t[-1];mu,mw,ids,solution,invariant=self.rays(order,end)
        background=np.load(previous.prior.EV/'accepted-ports-128.npz');lum=background['angular_luminosity'];h=float(background['h'])
        p=np.load(BEFORE/f'photons/steps-{steps}-reference-128.npz');gamma=1-1/np.sqrt(2);hp=end/steps
        packets=hp*np.tile([1-gamma,gamma],steps)[:,None]*p['accepted_angular_luminosity'];stage=p['accepted_angular_times']
        gx,gw=np.polynomial.legendre.leggauss(order);photon=[];energy=[]
        for now in t:
            count=int(round(now/h));n=int(round(now/hp))*2
            if count==0:photon.append(0.);energy.append(0.);continue
            tt=((np.arange(count)[:,None]+(gx+1)/2)*h).ravel()
            weight=((h*gw/2)[None,:,None]*lum[:count,None,ids]*mu*mw).reshape(len(tt),len(mu))
            tt=np.r_[tt,stage[:n]];weight=np.concatenate([weight,packets[:n,ids]*mu*mw])
            ages=np.maximum((now-tt)/end,0.)
            state=solution.sol(ages).reshape(3,len(mu),len(tt)).transpose(0,2,1)
            rp=self.r0*state[0];mp=state[1];cc=self.bg.metric(rp.ravel()/self.model.m.R)[3].reshape(rp.shape)
            kernel=state[2]/self.r0-mp*mp/(rp*cc)
            photon.append(float(G/C**4*np.sum(weight*kernel,dtype=LD)));energy.append(float(np.sum(weight,dtype=LD)))
        energy=np.array(energy);photon=np.array(photon)
        error=float(np.max(abs(energy-d['outer_cumulative_energy_erg']))/max(np.max(abs(energy)),1.));assert error<1e-12
        z=(gx+1)/2;_,N,b,_,_=self.bg.metric(self.r0/(z*self.model.m.R));kernel=float(np.sum(gw/(2*self.r0*N*b**1.5)))
        return photon,energy,dict(ray_invariant=invariant,emitted_energy_relative=error,unit_ADM_lapse_kernel_per_cm=kernel,actual_background_intervals_and_SDIRK_packets=True)


